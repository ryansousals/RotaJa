import { test, expect } from '@playwright/test';
import { config } from 'dotenv';
import { resolve } from 'node:path';
import { randomBytes } from 'node:crypto';
config({ path: resolve(process.cwd(), '../.env') });
// Espaça os cenários para respeitar os limites de acesso da API local.
test.beforeEach(async()=>{await new Promise(concluir=>setTimeout(concluir,15000));});
test('relatórios exportam e caixa diário registra diferença; logout revoga cookie', async ({ page }) => {
    await page.goto('/');
    await page.getByLabel('E-mail', { exact: true }).fill(process.env.ADMIN_EMAIL);
    await page.getByLabel('Senha', { exact: true }).fill(process.env.ADMIN_SENHA);
    await page.getByRole('button', { name: 'Entrar na plataforma' }).click();
    await expect(page.getByRole('button', { name: 'Sair pelo topo' })).toBeVisible();
    const suffix = randomBytes(4).toString('hex'), nome = 'Conferência visual ' + suffix;
    const r = await page.request.post('/api/cadastros/entregador', { data: { nom_usr: nome, eml_usr: `visual.${suffix}@teste.local`, senha: randomBytes(20).toString('hex'), doc_cpf: Array.from(randomBytes(11), b => b % 10).join(''), pla_moto: 'VIS1A23', tel_ent: '5589999990001' } });
    expect(r.status()).toBe(201);
    await page.getByRole('link', { name: 'Relatórios', exact: true }).click();
    await page.getByRole('combobox', { name: 'Relatório', exact: true }).selectOption('entregadores');
    await page.getByRole('button', { name: 'Gerar relatório', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'RELATÓRIO DE REPASSE DOS ENTREGADORES', exact: true })).toBeVisible();
    const download = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Exportar CSV', exact: true }).click();
    expect((await download).suggestedFilename()).toContain('entregadores');
    await page.pdf({ path: resolve(process.cwd(), '../entrega/relatorio-validacao.pdf'), format: 'A3', landscape: true, printBackground: true });
    await page.getByRole('link', { name: 'Caixa diário', exact: true }).click();
    await expect(page.getByRole('tab', { name: 'Fech. Pendentes', exact: true })).toHaveAttribute('aria-selected', 'true');
    await page.getByRole('button', { name: 'Abrir caixa', exact: true }).click();
    await page.getByRole('dialog').getByLabel('Entregador', { exact: false }).selectOption({ label: nome });
    await page.getByLabel('Valor da abertura').fill('50');
    await page.getByRole('button', { name: 'Salvar abertura' }).click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await page.getByRole('combobox', { name: 'Filtrar entregador', exact: true }).selectOption({ label: nome });
    await page.getByRole('tab', { name: 'Registro de Troco', exact: true }).click();
    await page.getByRole('button', { name: 'Registrar troco', exact: true }).click();
    await page.getByRole('dialog').getByLabel('Dinheiro', { exact: false }).fill('20');
    await page.getByLabel('Observação / comprovante').fill('Troco de teste visual');
    await page.getByRole('button', { name: 'Salvar lançamento', exact: true }).click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await expect(page.getByRole('cell', { name: 'Troco de teste visual Administrador', exact: true })).toBeVisible();
    await page.getByRole('tab', { name: 'Fech. Pendentes', exact: true }).click();
    await page.getByRole('button', { name: 'Registrar parcial de ' + nome, exact: true }).click();
    await page.getByRole('dialog').getByLabel('Dinheiro', { exact: false }).fill('10');
    await page.getByLabel('Observação / comprovante').fill('Parcial de teste visual');
    await page.getByRole('button', { name: 'Salvar lançamento', exact: true }).click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await page.getByRole('button', { name: 'Detalhar parciais de ' + nome, exact: true }).click();
    await expect(page.getByRole('dialog')).toContainText('Parcial de teste visual');
    await page.getByRole('button', { name: 'Fechar', exact: true }).click();
    await page.screenshot({ path: resolve(process.cwd(), '../entrega/registro-caixa.png'), fullPage: true });
    await page.getByRole('row').filter({ hasText: nome }).getByRole('button', { name: 'Fechar caixa de ' + nome, exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Fechamento diário', exact: true })).toBeVisible();
    await expect(page.getByRole('dialog').locator('.valor-negativo')).toContainText('60,00');
    await page.getByLabel('Dinheiro informado').fill('40');
    await page.getByLabel('Observações', { exact: true }).fill('Conferência visual: falta de dez reais registrada em teste.');
    await expect(page.getByRole('dialog').locator('.valor-negativo')).toContainText('20,00');
    await page.setViewportSize({ width: 1440, height: 1200 });
    await page.getByRole('heading', { name: 'Fechamento diário', exact: true }).scrollIntoViewIfNeeded();
    await page.screenshot({ path: resolve(process.cwd(), '../entrega/caixa-diario.png'), fullPage: true });
    await page.getByRole('button', { name: 'Salvar fechamento', exact: true }).click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await expect(page.getByRole('row').filter({ hasText: nome })).toContainText('Aguardando validação');
    await page.getByRole('row').filter({ hasText: nome }).getByRole('button', { name: 'Detalhes' }).click();
    await expect(page.getByRole('dialog')).toContainText('Conferência visual: falta de dez reais');
    await page.getByRole('button', { name: 'Fechar', exact: true }).click();
    await page.getByRole('row').filter({ hasText: nome }).getByRole('button', { name: 'Validar quitação' }).click();
    await page.getByLabel('Comprovante').fill('TESTE-VISUAL-' + suffix);
    await page.getByRole('button', { name: 'Confirmar quitação' }).click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await page.getByRole('tab', { name: 'Fech. Concluídos', exact: true }).click();
    await expect(page.getByRole('row').filter({ hasText: nome })).toContainText('Quitado');
    await page.getByRole('link', { name: 'Entregadores', exact: true }).click();
    await page.getByRole('button', { name: 'Excluir entregador ' + nome, exact: true }).click();
    await expect(page.getByRole('dialog')).toContainText('Tem certeza');
    await page.getByRole('button', { name: 'Confirmar exclusão', exact: true }).click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await expect(page.getByRole('button', { name: 'Excluir entregador ' + nome, exact: true })).toHaveCount(0);
    await page.setViewportSize({ width: 390, height: 844 });
    await expect(page.getByRole('button', { name: 'Sair pelo topo' })).toBeVisible();
    await page.getByRole('button', { name: 'Sair pelo topo' }).click();
    await expect(page.getByRole('button', { name: 'Entrar na plataforma' })).toBeVisible();
    expect((await page.context().cookies()).some(c => c.name === 'rotaja_sessao')).toBe(false);
    expect((await page.request.get('/api/autenticacao/eu')).status()).toBe(401);
    await page.reload();
    await expect(page.getByRole('button', { name: 'Entrar na plataforma' })).toBeVisible();
});
